// Package evasion provides compile-time string obfuscation and runtime EDR evasion primitives.
package evasion

// obfKey is the 16-byte XOR key used to obfuscate all sensitive strings.
// Changing this key requires regenerating all Obf() calls.
var obfKey = [16]byte{
	0xDE, 0xAD, 0xBE, 0xEF, 0xCA, 0xFE, 0xBA, 0xBE,
	0x13, 0x37, 0x42, 0x69, 0xAA, 0xBB, 0xCC, 0xDD,
}

// Obf XORs a byte slice (compile-time obfuscated string) with the key and returns the plaintext string.
// Usage: evasion.Obf([]byte{0x...}) — store sensitive strings as pre-XOR'd byte literals.
func Obf(data []byte) string {
	out := make([]byte, len(data))
	for i, b := range data {
		out[i] = b ^ obfKey[i%16]
	}
	return string(out)
}

// ObfBytes is Obf but returns []byte (useful for further processing).
func ObfBytes(data []byte) []byte {
	out := make([]byte, len(data))
	for i, b := range data {
		out[i] = b ^ obfKey[i%16]
	}
	return out
}

// MakeObf XORs a plaintext string with the key and returns the obfuscated bytes.
// Used during development to generate the byte literals to embed in source.
func MakeObf(s string) []byte {
	data := []byte(s)
	out := make([]byte, len(data))
	for i, b := range data {
		out[i] = b ^ obfKey[i%16]
	}
	return out
}

// ---- Pre-obfuscated sensitive string constants ----
// Generated with MakeObf() — never store plaintext in source.

// S returns the plaintext of a pre-obfuscated string constant.
// This is the primary API: evasion.S(evasion.SNtdll)
func S(data []byte) string { return Obf(data) }

